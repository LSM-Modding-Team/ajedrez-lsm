"""Bundle the static pages without network dependencies or build packages.

The HTML files remain editable. Marked blocks are refreshed from the shared
CSS/JS files; the rest of each page is preserved verbatim.
"""
from pathlib import Path
import base64
import hashlib
import json
import re
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
PAGES = sorted(ROOT.glob('*.html'))
RULES = next(ROOT.glob('reglas-*.js'))
DRAW = next(ROOT.glob('sorteo-*.js'))


def data_url(path, mime):
    return 'data:' + mime + ';base64,' + base64.b64encode(path.read_bytes()).decode()


def replace_bundle(html, kind, name, source_pattern, body):
    marked = rf'<!-- bundle:{re.escape(name)} -->.*?<!-- /bundle:{re.escape(name)} -->'
    block = f'<!-- bundle:{name} -->\n<{kind} data-bundle="{name}">\n{body}\n</{kind}>\n<!-- /bundle:{name} -->'
    pattern = marked if re.search(marked, html, re.S) else source_pattern
    return re.sub(pattern, lambda _: block, html, flags=re.S)


CSS = (ROOT / 'style.css').read_text()
BACKGROUND = 'data:image/svg+xml,' + quote((ROOT / 'chess-field.svg').read_text(), safe='')
CSS = re.sub(r'chess-field\.svg(?:\?[^\'"\s)]*)?', lambda _: BACKGROUND, CSS)
FAVICON = data_url(ROOT / 'favicon.svg', 'image/svg+xml')
SOUND = data_url(ROOT / 'assets/audio/wheel-tick.mp3', 'audio/mpeg')
DRAW_CODE = DRAW.read_text().replace("'assets/audio/wheel-tick.mp3'", json.dumps(SOUND))

REGISTER = """<!-- offline-shell -->
<script data-bundle="offline-shell">
// Install only after the first paint. Caches contain static files, never scores or names.
if ('serviceWorker' in navigator && location.protocol !== 'file:') {
  window.addEventListener('load', () => {
    const prepare = () => navigator.serviceWorker.register('sw.js', {updateViaCache:'none'})
      .then(() => navigator.serviceWorker.ready)
      .then(() => console.debug('ajedrez: static shell cached'))
      .catch(() => {});
    if ('requestIdleCallback' in window) requestIdleCallback(prepare, {timeout:2500});
    else setTimeout(prepare, 1000);
  }, {once:true});
}
</script>
<!-- /offline-shell -->"""

for page in PAGES:
    html = page.read_text()
    html = replace_bundle(html, 'style', 'style.css', r'<link\b[^>]*href="style\.css(?:\?[^\"]*)?"[^>]*>', CSS)
    if page.name == 'manual.html':
        html = replace_bundle(html, 'style', 'manual.css', r'<link\b[^>]*href="manual\.css(?:\?[^\"]*)?"[^>]*>', (ROOT / 'manual.css').read_text())
    html = replace_bundle(html, 'script', 'rules', r'<script\b[^>]*src="reglas-[^\"]+"[^>]*></script>', RULES.read_text())
    html = replace_bundle(html, 'script', 'draw', r'<script\b[^>]*src="sorteo-[^\"]+"[^>]*></script>', DRAW_CODE)
    html = re.sub(r'(<link\b[^>]*rel="icon"[^>]*href=")[^"]+("[^>]*>)', lambda m: m[1] + FAVICON + m[2], html)
    if '<!-- offline-shell -->' in html:
        html = re.sub(r'<!-- offline-shell -->.*?<!-- /offline-shell -->', lambda _: REGISTER, html, flags=re.S)
    else:
        html = html.replace('</body>', REGISTER + '\n</body>')
    page.write_text(html)

version = hashlib.sha256(b''.join(p.read_bytes() for p in PAGES)).hexdigest()[:16]
paths = [p.name for p in PAGES]
worker = """// Generated by scripts/build_pages.py. Cache only this application's static shell.
const PREFIX = 'ajedrez-lsm-shell-';
const CACHE = PREFIX + '__VERSION__';
const PAGES = __PAGES__;
const ROOT = new URL('./', self.location.href);
const canonical = name => new URL(name, ROOT).href;
self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await cache.addAll(PAGES.map(name => new Request(canonical(name), {cache:'reload'})));
    await self.skipWaiting();
  })());
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) if (name.startsWith(PREFIX) && name !== CACHE) await caches.delete(name);
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET' || event.request.mode !== 'navigate') return;
  const url = new URL(event.request.url);
  if (url.origin !== ROOT.origin || !url.pathname.startsWith(ROOT.pathname)) return;
  const name = url.pathname.slice(ROOT.pathname.length) || 'index.html';
  if (!PAGES.includes(name)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    // The category query belongs to location.search, not to the static HTML cache key.
    const cached = await cache.match(canonical(name));
    return cached || fetch(event.request);
  })());
});
""".replace('__VERSION__', version).replace('__PAGES__', json.dumps(paths))
(ROOT / 'sw.js').write_text(worker)
print(f'Built {len(PAGES)} self-contained pages; offline shell {version}.')
